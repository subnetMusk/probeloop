// Generates the TypeScript types of the API from the contract the backend exports:
//   docker run --rm -v "$PWD/src/shared/api/contract:/out" probeloop-backend:dev \
//     python -m probeloop.api.contract /out
//   npm run gen:types
// CI regenerates both and fails if the committed files differ.
import { readFile, writeFile, mkdir } from 'node:fs/promises'

import { compile } from 'json-schema-to-typescript'
import openapiTS, { astToString } from 'openapi-typescript'

const contract = new URL('../src/shared/api/contract/', import.meta.url)
const out = new URL('../src/shared/api/types/', import.meta.url)
const banner =
  '/* Generated by scripts/generate-types.mjs from src/shared/api/contract. Do not edit. */'

// Pydantic gives every field a title, which would become a type alias of its own.
function dropFieldTitles(node, isDefinition = false) {
  if (Array.isArray(node)) return node.map((item) => dropFieldTitles(item))
  if (node === null || typeof node !== 'object') return node
  const copy = {}
  for (const [key, value] of Object.entries(node)) {
    if (key === 'title' && !isDefinition) continue
    if (key === '$defs') {
      copy[key] = Object.fromEntries(
        Object.entries(value).map(([name, def]) => [name, dropFieldTitles(def, true)]),
      )
    } else {
      copy[key] = dropFieldTitles(value)
    }
  }
  return copy
}

await mkdir(out, { recursive: true })
for (const [schema, target] of [
  ['ws-client.schema.json', 'ws-client.ts'],
  ['ws-server.schema.json', 'ws-server.ts'],
]) {
  const json = dropFieldTitles(JSON.parse(await readFile(new URL(schema, contract), 'utf8')), true)
  const ts = await compile(json, json.title, { bannerComment: banner, additionalProperties: false })
  await writeFile(new URL(target, out), ts)
}
const openapi = JSON.parse(await readFile(new URL('openapi.json', contract), 'utf8'))
await writeFile(
  new URL('rest.ts', out),
  `${banner}\n\n${astToString(await openapiTS(openapi, { defaultNonNullable: false }))}`,
)
